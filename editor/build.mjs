// Builds internal/web/static/editor.js and, beside it, editor-licenses.txt:
// the licence of every package that ends up inside the bundle, because MIT
// asks for its notice to travel with the code. The list is read from what
// esbuild actually bundled, not from package.json, so it cannot drift.
// Run: npm run build
import * as esbuild from 'esbuild'
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const out = '../internal/web/static/editor.js'
const result = await esbuild.build({
  entryPoints: ['src/editor.js'],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  legalComments: 'none',
  banner: { js: '/*! Hearth rich-text editor, built from editor/ in the Hearth repository. Third-party licences: editor-licenses.txt */' },
  metafile: true,
  outfile: out,
})

const packages = new Set()
for (const input of Object.keys(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].inputs)) {
  if (!input.startsWith('node_modules/')) continue
  const parts = input.slice('node_modules/'.length).split('/')
  packages.add(parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0])
}

const sections = []
for (const name of [...packages].sort()) {
  const dir = join('node_modules', name)
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  if (pkg.license !== 'MIT') throw new Error(`${name} is ${pkg.license}, not MIT: check it before shipping`)
  const file = readdirSync(dir).find((f) => /^licen[cs]e/i.test(f))
  const text = file ? readFileSync(join(dir, file), 'utf8').trim() : `MIT licence (no licence file shipped in the package; see ${pkg.repository?.url || pkg.homepage || 'npm'})`
  sections.push(`${name}@${pkg.version} (${pkg.license})\n${'-'.repeat(60)}\n${text}`)
}
writeFileSync(
  '../internal/web/static/editor-licenses.txt',
  `Third-party software inside editor.js (${sections.length} packages, all MIT).\nGenerated by editor/build.mjs; do not edit by hand.\n\n${sections.join('\n\n\n')}\n`,
)
console.log(`editor.js built; ${sections.length} packages, all MIT, listed in editor-licenses.txt`)
