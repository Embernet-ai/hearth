package crm

import "testing"

func TestPhoneE164(t *testing.T) {
	for in, want := range map[string]string{
		"(216) 555-0142":     "+12165550142",
		"216-555-0142":       "+12165550142",
		"+1 216 555 0142":    "+12165550142",
		"1-216-555-0142":     "+12165550142",
		"+52 492 555 0100":   "+524925550100",
		"0052 492 555 0100":  "+524925550100",
		"  +44 20 7946 0958": "+442079460958",
		"555-0142":           "",
		"492 555 0100 12":    "",
		"":                   "",
		"ext 100":            "",
	} {
		if got := PhoneE164(in); got != want {
			t.Errorf("PhoneE164(%q) = %q, want %q", in, got, want)
		}
	}
}
